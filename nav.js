(function () {
  var toggle = document.querySelector(".nav-toggle");
  var menu = document.getElementById("nav-menu");

  if (!toggle || !menu) return;

  function setOpen(open) {
    menu.classList.toggle("is-open", open);
    toggle.classList.toggle("is-open", open);
    toggle.setAttribute("aria-expanded", open ? "true" : "false");
    toggle.setAttribute("aria-label", open ? "Close menu" : "Open menu");
  }

  toggle.addEventListener("click", function (event) {
    event.stopPropagation();
    setOpen(!menu.classList.contains("is-open"));
  });

  /* Close after picking a destination — including in-page #work jumps, where
     no navigation happens to close it for us. */
  menu.addEventListener("click", function (event) {
    if (event.target.closest("a")) setOpen(false);
  });

  document.addEventListener("click", function (event) {
    if (!menu.classList.contains("is-open")) return;
    if (!menu.contains(event.target)) setOpen(false);
  });

  document.addEventListener("keydown", function (event) {
    if (event.key === "Escape") setOpen(false);
  });

  /* Resizing to desktop hides the toggle, so an open panel would otherwise be
     stranded with no way to dismiss it. */
  var desktop = window.matchMedia("(min-width: 769px)");
  var onChange = function (event) {
    if (event.matches) setOpen(false);
  };

  if (desktop.addEventListener) {
    desktop.addEventListener("change", onChange);
  } else if (desktop.addListener) {
    desktop.addListener(onChange);
  }
})();

